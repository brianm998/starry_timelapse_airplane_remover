  if(exists $codecs->{$name}{real_name}) {
    print OUT "    case $codecs->{$name}{name} = \"$codecs->{$name}{real_name}\"\n";
  } else {
    print OUT "    case $name\n";
  }
}

print OUT "\n\n";

