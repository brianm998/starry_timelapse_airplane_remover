print OUT "    public var isIntraFrameOnly: Bool {\n";
print OUT "        switch self {\n";
foreach my $name (keys %$codecs) {
  if (exists $codecs->{$name}{real_name}) {
    print OUT "        case .$codecs->{$name}{name}:\n";
  } else {
    print OUT "        case .$name:\n";
