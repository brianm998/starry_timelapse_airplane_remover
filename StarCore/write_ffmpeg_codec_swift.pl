my $codecs = {};

while(<FH>) { 
  $started = 1 if(/^\s*-------\s*$/);
  if($started && /^\s*([D.])([E.])([VASDT.])([I.])([L.])([S.])\s+(\w+)\s+(.*)$/) {

    my ($decoding,
	$encoding,
	$codec_type,
	$intra_frame_only,
	$lossy,
	$lossless,
	$name,
	$description) = ($1 ne '.', $2 ne '.', $3, $4 ne '.', $5 ne '.', $6, $7, $8);

    my $encoders;

    if ($description =~ /\(encoders: ([^\)]+)\s+\)/) {
      # decode which encoders this codec supports
      my @list = split / /, $1;
      $encoders = \@list;
    } else {
      # no listed encoders, assume just one with the same name as codec
      $encoders = [$name];
    }

    $description =~ s/\([^)]+\)//g;
    $description =~ s/\s+$//g;

    if ($name =~ /^\s*\d/) {
	$codecs->{$name} = {name => "_".$name,
			    real_name => $name,
			    decoding => $decoding,
			    encoding => $encoding,
			    codec_type => $codec_type,
			    intra_frame_only => $intra_frame_only,
			    lossy => $lossy,
			    lossless => $lossless,
			    encoders => $encoders,
			    description => $description};
    } else {
	$codecs->{$name} = {decoding => $decoding,
			    encoding => $encoding,
			    codec_type => $codec_type,
			    intra_frame_only => $intra_frame_only,
			    lossy => $lossy,
			    lossless => $lossless,
			    encoders => $encoders,
			    name => $name,
			    description => $description};
    }
  }
}
close FH;

print OUT "import Foundation\n\n";

