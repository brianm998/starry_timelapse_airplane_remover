#!/usr/bin/perl

use strict;

# Which ffmpeg to describe: FFMPEG, or the one ../ffmpeg/build.sh --install left in the repository.
my $ffmpeg = $ENV{FFMPEG} // '../external_binaries/bin/ffmpeg';

# Encoders the ffmpeg above cannot have, because it is built for a platform that cannot build
# them (NVENC is not available on macOS), listed in a file so the dialog can still offer them.
my $extra_file = $ENV{EXTRA_ENCODERS} // 'ffmpeg_extra_encoders.txt';

open (FH, "$ffmpeg -codecs 2>/dev/null |") || die "cannot read codecs: $!\n";

open OUT, ">Sources/StarCore/FFmpegCodec.swift";

my $started = 0;

my $codecs = {};

while(<FH>) { 
  $started = 1 if(/^\s*-------\s*$/);
  if($started && /^\s*([D.])([E.])([VASDT.])([I.])([L.])([S.])\s+(\w+)\s+(.*)$/) {

    my ($decoding,
	$encoding,
	$codec_type,
	$intra_frame_only,
	$lossy,
	$lossless,
	$name,
	$description) = ($1 ne '.', $2 ne '.', $3, $4 ne '.', $5 ne '.', $6, $7, $8);

    my $encoders;

    # ffmpeg 8 and before pad the list, "(encoders: a b )"; ffmpeg 9 does not, "(encoders: a b)".
    # Accept both: matching only the padded form quietly turns every codec into one whose single
    # encoder is named after itself, which is how libx264 once vanished from the table.
    if ($description =~ /\(encoders:\s*([^\)]*?)\s*\)/) {
      # decode which encoders this codec supports
      my @list = split /\s+/, $1;
      $encoders = \@list;
    } else {
      # no listed encoders, assume just one with the same name as codec
      $encoders = [$name];
    }

    $description =~ s/\([^)]+\)//g;
    $description =~ s/\s+$//g;

    if ($name =~ /^\s*\d/) {
	$codecs->{$name} = {name => "_".$name,
			    real_name => $name,
			    decoding => $decoding,
			    encoding => $encoding,
			    codec_type => $codec_type,
			    intra_frame_only => $intra_frame_only,
			    lossy => $lossy,
			    lossless => $lossless,
			    encoders => $encoders,
			    description => $description};
    } else {
	$codecs->{$name} = {decoding => $decoding,
			    encoding => $encoding,
			    codec_type => $codec_type,
			    intra_frame_only => $intra_frame_only,
			    lossy => $lossy,
			    lossless => $lossless,
			    encoders => $encoders,
			    name => $name,
			    description => $description};
    }
  }
}
close FH;

# name => {codec, description, formats => [ordered]} for encoders taken from the supplement
my $extra = {};
if (open(my $xf, '<', $extra_file)) {
  while (<$xf>) {
    next if /^\s*(#|$)/;
    chomp;
    my ($enc, $codec, $description, $formats) = map { s/^\s+|\s+$//gr } split /\|/, $_, 4;
    die "$extra_file: bad line: $_\n" unless defined $formats;
    die "$extra_file: $enc names codec $codec, which this ffmpeg does not know\n"
      unless exists $codecs->{$codec};
    $extra->{$enc} = {codec => $codec,
		      description => $description,
		      formats => [split /\s+/, $formats]};
    my $list = $codecs->{$codec}{encoders};
    push @$list, $enc unless grep { $_ eq $enc } @$list;
    $codecs->{$codec}{encoding} = 1;
  }
  close $xf;
}

print OUT "import Foundation\n\n";

print OUT "// Auto generated by $0\n\n";
print OUT "// DO NOT EDIT BY HAND\n";
print OUT "// DO NOT EDIT BY HAND\n";
print OUT "// DO NOT EDIT BY HAND\n\n";

print OUT "public enum FFmpegCodec: String, CaseIterable, Codable, Sendable {\n";
foreach my $name (sort keys %$codecs) {
  if(exists $codecs->{$name}{real_name}) {
    print OUT "    case $codecs->{$name}{name} = \"$codecs->{$name}{real_name}\"\n";
  } else {
    print OUT "    case $name\n";
  }
}

print OUT "\n\n";

print OUT "    public var canDecode: Bool {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$codecs) {
  if (exists $codecs->{$name}{real_name}) {
    print OUT "        case .$codecs->{$name}{name}:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  if ($codecs->{$name}{decoding} == 1) {
    print OUT "            true\n";
  } else {
    print OUT "            false\n";
  }
}
print OUT "        }\n";
print OUT "    }\n\n";


print OUT "    public var canEncode: Bool {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$codecs) {
  if (exists $codecs->{$name}{real_name}) {
    print OUT "        case .$codecs->{$name}{name}:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  if($codecs->{$name}{encoding} == 1) {
    print OUT "            true\n";
  } else {
    print OUT "            false\n";
  }
}
print OUT "        }\n";
print OUT "    }\n\n";

print OUT "    public var isIntraFrameOnly: Bool {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$codecs) {
  if (exists $codecs->{$name}{real_name}) {
    print OUT "        case .$codecs->{$name}{name}:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  if($codecs->{$name}{intra_frame_only} == 1) {
    print OUT "            true\n";
  } else {
    print OUT "            false\n";
  }
}
print OUT "        }\n";
print OUT "    }\n\n";


print OUT "    public var isLossy: Bool {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$codecs) {
  if (exists $codecs->{$name}{real_name}) {
    print OUT "        case .$codecs->{$name}{name}:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  if($codecs->{$name}{lossy} == 1) {
    print OUT "            true\n";
  } else {
    print OUT "            false\n";
  }
}
print OUT "        }\n";
print OUT "    }\n\n";


print OUT "    public var isLossless: Bool {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$codecs) {
  if (exists $codecs->{$name}{real_name}) {
    print OUT "        case .$codecs->{$name}{name}:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  if($codecs->{$name}{lossless} == 1) {
    print OUT "            true\n";
  } else {
    print OUT "            false\n";
  }
}
print OUT "        }\n";
print OUT "    }\n\n";

print OUT "    public var description: String {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$codecs) {
  if (exists $codecs->{$name}{real_name}) {
    print OUT "        case .$codecs->{$name}{name}:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  print OUT "            \"$codecs->{$name}{description}\"\n";
}
print OUT "        }\n";
print OUT "    }\n\n";


print OUT "    public var type: CodecType {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$codecs) {
  if (exists $codecs->{$name}{real_name}) {
    print OUT "        case .$codecs->{$name}{name}:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  my $type = $codecs->{$name}{codec_type};
  if($type eq 'V') {
      print OUT "            .video\n";
  } elsif($type eq 'A') {
      print OUT "            .audio\n";
  } elsif($type eq 'S') {
      print OUT "            .subtitle\n";
  } elsif($type eq 'D') {
      print OUT "            .data\n";
  } elsif($type eq 'T') {
      print OUT "            .attachment\n";
  } else {
      print OUT "            .none\n";
  }
}
print OUT "        }\n";
print OUT "    }\n\n";

print OUT "    public var encoders: [FFmpegEncoder] {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$codecs) {
  if (exists $codecs->{$name}{real_name}) {
    print OUT "        case .$codecs->{$name}{name}:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  # `map` aliases $_ to the element, so substituting on $_ would rewrite the encoder's real name
  # in the list (libvpx-vp9 became libvpx_vp9, which is not an encoder ffmpeg has, and the
  # lookup of its pixel formats below then found nothing).  Work on a copy.
  my @list = join ", ", map {
    my $encoder = $_;
    if ($encoder =~ /-/) {
      (my $swift = $encoder) =~ s/-/_/g;
      ".$swift";
    } elsif($encoder =~ /^\s*\d/) {
       "._$encoder";
    } else {
       ".$encoder";
    }
  } @{$codecs->{$name}{encoders}};
  print OUT "            [@list]\n";
}
print OUT "        }\n";
print OUT "    }\n\n";

my $extra_info = {};

my $encoders = {};

foreach my $name (sort keys %$codecs) {
  my $real_name = $name;
  $real_name = $codecs->{$name}{name} if (exists $codecs->{$name}{real_name});


  ## XXX this needs to separate by encoder
  foreach my $encoder (@{$codecs->{$name}{encoders}}) {

    my @formats;                # in the order ffmpeg lists them, first is the encoder's preference
    my %seen;
    my $short_description = undef;
    if (exists $extra->{$encoder}) {
      @formats = @{$extra->{$encoder}{formats}};
      $short_description = $extra->{$encoder}{description};
    } else {
      open (FH, "$ffmpeg -h encoder=$encoder 2>/dev/null |") || die "cannot read encoder $encoder: $!\n";
      while (<FH>) {
	if (/Supported pixel formats:\s+(.*)/) {
	  push @formats, split /\s+/, $1;
	} elsif (/Encoder[^\]]+\[([^\]]+)\]:/) {
	  $short_description = $1;
	}
      }
      close FH;
    }
    # The first is what the dialog selects when the encoder is chosen, so keep ffmpeg's order
    # (a hash here once made it effectively random, and changed on every run).
    my @swift = map { /^\s*\d/ ? "._$_" : ".$_" } grep { !$seen{$_}++ } @formats;
    $encoders->{$encoder}{supported_line} = "[" . join(", ", @swift) . "]";
    $encoders->{$encoder}{description} = $short_description;
  }
}

print OUT "    public var name: String? {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$codecs) {
  my $real_name = $name;
  $real_name = $codecs->{$name}{name} if (exists $codecs->{$name}{real_name});
  print OUT "        case .$real_name:\n";
  if(exists $extra_info->{$name}{description}) {
    my $value = $extra_info->{$name}{description};
    $value =~ s/\"/\\\"/g;
    print OUT "            return \"$value\"\n";
  } else {
    print OUT "            return nil\n";
  }
}
print OUT "        }\n";
print OUT "    }\n";
print OUT "}\n\n";

print OUT "public enum CodecType: Codable {\n";
print OUT "    case video\n";
print OUT "    case audio\n";
print OUT "    case subtitle\n";
print OUT "    case data\n";
print OUT "    case attachment\n";
print OUT "    case none\n";
print OUT "}\n\n";

print OUT "public enum FFmpegEncoder: String, CaseIterable, Codable, Sendable {\n";

foreach my $name (sort keys %$encoders) {
  if ($name =~ /-/) {
    my $updated_name = $name;
    $updated_name =~ s/-/_/g;
    print OUT "    case $updated_name = \"$name\"\n";
  } elsif ($name =~ /^\s*\d/) {
    print OUT "    case _$name = \"$name\"\n";
  } else {
    print OUT "    case $name\n";
  }
}


print OUT "    public var pixelFormats: [FFmpegPixelFormat] {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$encoders) {
  if ($name =~ /-/) {
    my $updated_name = $name;
    $updated_name =~ s/-/_/g;
    print OUT "        case .$updated_name:\n";
  } elsif ($name =~ /^\s*\d/) {
    print OUT "        case ._$name:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  print OUT "            $encoders->{$name}{supported_line}\n";
}
print OUT "        }\n";
print OUT "    }\n\n";


print OUT "    public var description: String {\n";
print OUT "        switch self {\n";
foreach my $name (sort keys %$encoders) {
  if ($name =~ /-/) {
    my $updated_name = $name;
    $updated_name =~ s/-/_/g;
    print OUT "        case .$updated_name:\n";
  } elsif ($name =~ /^\s*\d/) {
    print OUT "        case ._$name:\n";
  } else {
    print OUT "        case .$name:\n";
  }
  my $description = $encoders->{$name}{description};
  $description =~ s/\"/\\\"/g;
  print OUT "            return \"$description\"\n";
}
print OUT "        }\n";
print OUT "    }\n\n";


print OUT "}\n";
